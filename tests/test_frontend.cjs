const assert=require('node:assert/strict');
const fs=require('node:fs');
const {parseScript,esc,numeric}=require('../dist/app.js');
const steps=parseScript('# title\nmass waitforcombat completion\nsleep 0.5\nmass sendkey W 0.2\np2 tp XYZ(-15.3, 20, 0)');
assert.deepEqual(steps.map(s=>s.op),['wait_combat','sleep','key','teleport']);
assert.deepEqual(steps[3].xyz,[-15.3,20,0]);
for(const source of ['import os','mass tp closestmob','loop {','sleep 61','mass sendkey W 10','mass tp XYZ(NaN, 0, 0)','mass sendkey NOT_A_KEY 1','p0 sendkey X 0.1'])assert.throws(()=>parseScript(source));
assert.throws(()=>parseScript('sleep 0\n'.repeat(201)));
assert.throws(()=>numeric(Infinity));assert.throws(()=>numeric(true));
assert.equal(esc('<script>"&'), '&lt;script&gt;&quot;&amp;');
const html=fs.readFileSync('dist/index.html','utf8'),js=fs.readFileSync('dist/app.js','utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'Duplicate DOM ids');
for(const match of js.matchAll(/\$\('([^']+)'\)/g))assert(ids.includes(match[1]),'Missing DOM id '+match[1]);
for(const asset of ['app.js','style.css','sources.json'])assert(fs.existsSync('dist/'+asset));
assert(JSON.parse(fs.readFileSync('dist/sources.json')).sources.length>=8);
console.log('Frontend parser, escaping and DOM contract checks passed.');
const {mwCombo,mwValidate,mwUi,MW_DEFAULTS,MW_UI_DEFAULTS}=require('../dist/settings.js');
assert.equal(mwCombo('shift + ctrl + H'),'Ctrl+Shift+H');
for(const key of ['H','Ctrl+F12','Win+H','Ctrl+Ctrl+H'])assert.throws(()=>mwCombo(key));
const changed=structuredClone(MW_DEFAULTS);changed.bindings.hook=changed.bindings.scan;assert.throws(()=>mwValidate(changed));changed.bindings.hook='';assert.equal(mwValidate(changed).bindings.hook,'');
assert.throws(()=>mwValidate({...MW_DEFAULTS,key_seconds:Infinity}));
assert.throws(()=>mwUi({...MW_UI_DEFAULTS,accent:'invalid'}));
const settingsJs=fs.readFileSync('dist/settings.js','utf8');
for(const match of settingsJs.matchAll(/\$\('([^']+)'\)/g))if(!match[1].endsWith('-'))assert(ids.includes(match[1]),'Missing Settings DOM id '+match[1]);
console.log('Settings import validation, conflicts and DOM contracts passed.');
